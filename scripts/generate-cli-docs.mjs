#!/usr/bin/env node
/**
 * Generate docs/personas/ai-agent-ops/cli-ai-agents.md from the shared operation registry.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const COMMON_DIST = path.join(ROOT, 'packages/common/dist/operations/index.js');
const OUTPUT_PATH = path.join(ROOT, 'docs/personas/ai-agent-ops/cli-ai-agents.md');

async function loadRegistry() {
  if (!fs.existsSync(COMMON_DIST)) {
    throw new Error(
      `Built common package not found at ${COMMON_DIST}. Run "pnpm --filter @lightdash-tools/common build" first.`,
    );
  }
  return import(COMMON_DIST);
}

function formatProfiles(profiles) {
  return profiles.map((profile) => `\`${profile}\``).join(', ');
}

function generateMarkdown(operations) {
  const aiAgentOps = operations
    .filter((operation) => operation.id.startsWith('ai-agents.'))
    .sort((a, b) => a.id.localeCompare(b.id));

  const lines = [
    '# CLI reference: AI agents',
    '',
    '<!-- Generated by scripts/generate-cli-docs.mjs. Do not edit by hand. -->',
    '',
    'Commands and HTTP mappings for AI agent operations from the shared operation registry.',
    '',
    '| Operation ID | CLI command | HTTP | Profiles | Summary |',
    '| --- | --- | --- | --- | --- |',
  ];

  for (const operation of aiAgentOps) {
    const http = `\`${operation.http.method} ${operation.http.path}\``;
    const cli = operation.cli?.commandPath
      ? `\`lightdash-tools ${operation.cli.commandPath}\``
      : '—';
    const summary = operation.summary.replace(/\|/g, '\\|');
    lines.push(
      `| \`${operation.id}\` | ${cli} | ${http} | ${formatProfiles(operation.profiles)} | ${summary} |`,
    );
  }

  lines.push('');
  lines.push('## Regenerate');
  lines.push('');
  lines.push('```bash');
  lines.push('pnpm --filter @lightdash-tools/common build');
  lines.push('node scripts/generate-cli-docs.mjs');
  lines.push('```');
  lines.push('');

  return `${lines.join('\n')}`;
}

async function main() {
  const { listOperations } = await loadRegistry();
  const markdown = generateMarkdown(listOperations());
  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(OUTPUT_PATH, markdown, 'utf-8');
  console.log(`Wrote ${OUTPUT_PATH}`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
});
